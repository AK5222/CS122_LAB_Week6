static inline void send_word(uint16_t w) {
    gpio_put(PIN_CS, 0);
    sleep_us(2);
    spi_write16_blocking(SPI_PORT, &w, 1);
    sleep_us(2);
    gpio_put(PIN_CS, 1);
    sleep_us(5);
}

// Pick which sprite pixel goes to destination (x, y) based on rotation.
//   rot 0:   0 degrees     (no rotation)
//   rot 1:  90 degrees CW
//   rot 2: 180 degrees
//   rot 3: 270 degrees CW
static inline uint16_t rotated_pixel(int rot, int x, int y) {
    switch (rot) {
        case 1:  return SPRITE[(15 - x) * 16 + y];
        case 2:  return SPRITE[(15 - y) * 16 + (15 - x)];
        case 3:  return SPRITE[x * 16 + (15 - y)];
        default: return SPRITE[y * 16 + x];
    }
}

int main() {
    stdio_init_all();

    spi_init(SPI_PORT, 50 * 1000);   // 50 kHz — slow & reliable
    spi_set_format(SPI_PORT, 16, SPI_CPOL_0, SPI_CPHA_0, SPI_MSB_FIRST);

    gpio_set_function(PIN_SCK,  GPIO_FUNC_SPI);
    gpio_set_function(PIN_MOSI, GPIO_FUNC_SPI);

    gpio_init(PIN_CS);
    gpio_set_dir(PIN_CS, GPIO_OUT);
    gpio_put(PIN_CS, 1);

    int rotation = 0;
    absolute_time_t next_rotate = make_timeout_time_ms(1000);

    while (true) {
        // Send one full 16x16 frame in current rotation.
        for (int y = 0; y < 16; y++) {
            for (int x = 0; x < 16; x++) {
                send_word(rotated_pixel(rotation, x, y));
            }
        }

        // Every 1 second, advance to the next 90-degree rotation.
        if (time_reached(next_rotate)) {
            rotation = (rotation + 1) & 3;
            next_rotate = make_timeout_time_ms(1000);
        }

        sleep_ms(50);
    }
}
